#!/bin/sh
# Checks the rotating JWT key ring over HTTP (phase 2 of
# docs/jwt-keys-design.md): samples/03-tenants with its keys generated and
# kept in the control database, rotated in seconds instead of days.
#
#   JWT_KEY_STORE=db JWT_ROTATE_SECONDS=3 JWT_PROPAGATION_SECONDS=2 \
#   JWT_RELOAD_SECONDS=1 TenantApiSample [port] --reset
#   sh tools/http_scenarios_jwt_rotation.sh [port [port2]]   (default 9351)
#
# JWT_KEY_STORE=redis keeps the keys in Redis instead (REDIS_HOST,
# REDIS_PORT, JWT_REDIS_PREFIX). One ring per tenant (phase 3): a kid is
# "<tenant>/<16 hex>". CONTROL_DB, the sample's control.sqlite (db mode),
# lets this script read acme's key and try it on a token claiming globex. With port2, a second instance of the
# sample on the same store (started after the first, without --reset): the
# two must sign with the same key and verify each other's tokens, also
# after both raced for the next generation.
#
# The keys are generated by the sample, so this script never signs with
# them: it takes the login's tokens, reads their kid, and logs in again
# until the kid changes (the first key is born when the server starts, an
# unknown time before this script; the pending state is checked by the unit
# tests, which own the clock). A token of the previous key must keep
# verifying after the next one signs. Tokens without kid verify with the
# legacy secret (JWT_SECRET, the sample's default). ROTATE and PROPAGATION
# bound the wait; they must match the server's.
# Exit code 0 only if every check passed.
PORT="${1:-9351}"
PORT2="${2:-}"
BASE="http://127.0.0.1:$PORT"
SECRET="${JWT_SECRET:-development-secret-change-me}"
ROTATE="${JWT_ROTATE_SECONDS:-3}"
PROPAGATION="${JWT_PROPAGATION_SECONDS:-2}"
T="$(mktemp -d)"
FAILS=0
CHECKS=0

PY=python3
$PY -c "" >/dev/null 2>&1 || PY=python

req() {
  M="$1"; P="$2"; B="$3"; shift 3 2>/dev/null || shift $#
  if [ -n "$B" ]; then
    curl -s -X "$M" -o "$T/body" -w '%{http_code}' -H 'Content-Type: application/json' \
      --data-binary "$B" "$@" "$BASE$P" > "$T/status"
  else
    curl -s -X "$M" -o "$T/body" -w '%{http_code}' "$@" "$BASE$P" > "$T/status"
  fi
}
ok()   { CHECKS=$((CHECKS + 1)); }
fail() { CHECKS=$((CHECKS + 1)); FAILS=$((FAILS + 1)); echo "FAIL: $1"; }
status_is() { [ "$(cat "$T/status")" = "$1" ] && ok || fail "$2: status $(cat "$T/status"), expected $1 (body: $(cat "$T/body"))"; }
body_is()   { [ "$(cat "$T/body")" = "$1" ] && ok || fail "$2: body $(cat "$T/body"), expected $1"; }

# login TENANT USER -> prints the token ('' when refused)
login() {
  req POST /auth/login "{\"tenant\":\"$1\",\"user\":\"$2\"}"
  sed -n 's/.*"token":"\([^"]*\)".*/\1/p' "$T/body"
}
# kid TOKEN -> the header's kid ('' without one)
kid() {
  $PY -c '
import sys, base64, json
h = sys.argv[1].split(".")[0]
print(json.loads(base64.urlsafe_b64decode(h + "=" * (-len(h) % 4))).get("kid", ""))' "$1"
}
# sign_header HEADER_JSON CLAIMS_JSON SECRET -> an HS256 token, exp one hour ahead
sign_header() {
  $PY -c '
import sys, hmac, hashlib, base64, json, time
b = lambda d: base64.urlsafe_b64encode(d).rstrip(b"=").decode()
claims = json.loads(sys.argv[2]); claims["exp"] = int(time.time()) + 3600
h = b(sys.argv[1].encode())
p = b(json.dumps(claims).encode())
s = b(hmac.new(sys.argv[3].encode(), (h + "." + p).encode(), hashlib.sha256).digest())
print(h + "." + p + "." + s)' "$1" "$2" "$3"
}
# on2 COMMAND... -> the command against the second instance
on2() { SAVED="$BASE"; BASE="http://127.0.0.1:$PORT2"; "$@"; BASE="$SAVED"; }
is_hex16() { echo "$1" | grep -qE '^[0-9a-f]{16}$'; }
# tenant_kid TENANT KID: KID is TENANT/<16 hex>
tenant_kid() { echo "$2" | grep -qE "^$1/[0-9a-f]{16}\$"; }

# --- the first key: generated at startup, signs at once
TOKEN1="$(login acme ana)"
[ -n "$TOKEN1" ] && ok || fail "login: $(cat "$T/body")"
KID1="$(kid "$TOKEN1")"
tenant_kid acme "$KID1" && ok || fail "acme's kid is acme/<16 hex> (got '$KID1')"
req GET /tenant "" -H "Authorization: Bearer $TOKEN1"
status_is 200 "a token of the first key"
body_is '{"tenant":"acme","mode":"dedicated"}' "a token of the first key"
[ "$(kid "$(login acme bia)")" = "$KID1" ] && ok || fail "the same key signs every acme login"
KIDG="$(kid "$(login globex bia)")"
tenant_kid globex "$KIDG" && ok || fail "globex has its own key (got '$KIDG')"
[ "${KIDG#globex/}" != "${KID1#acme/}" ] && ok || fail "two tenants, two keys"

# --- a tenant's key can't sign for another tenant (needs its secret: db mode)
if [ -n "$CONTROL_DB" ]; then
  ACME_SECRET="$($PY -c '
import sqlite3, sys
c = sqlite3.connect(sys.argv[1])
print(c.execute("SELECT SECRET FROM JWT_KEYS WHERE KID = ?", (sys.argv[2],)).fetchone()[0])' "$CONTROL_DB" "$KID1")"
  req GET /tenant "" -H "Authorization: Bearer $(sign_header "{\"alg\":\"HS256\",\"typ\":\"JWT\",\"kid\":\"$KID1\"}" '{"sub":"ana","tenant_id":"acme"}' "$ACME_SECRET")"
  status_is 200 "acme's key, read from the store, signs acme's token"
  req GET /tenant "" -H "Authorization: Bearer $(sign_header "{\"alg\":\"HS256\",\"typ\":\"JWT\",\"kid\":\"$KID1\"}" '{"sub":"ana","tenant_id":"globex"}' "$ACME_SECRET")"
  status_is 401 "acme's key on a token claiming globex"
  body_is '{"error":"Invalid or expired token."}' "acme's key on a token claiming globex"
  req GET /tenant "" -H "Authorization: Bearer $(sign_header "{\"alg\":\"HS256\",\"typ\":\"JWT\",\"kid\":\"$KIDG\"}" '{"sub":"ana","tenant_id":"globex"}' "$ACME_SECRET")"
  status_is 401 "globex's kid with acme's secret"
fi
req GET /tenant "" -H "Authorization: Bearer $(sign_header '{"alg":"HS256","typ":"JWT","kid":"wayne/0123456789abcdef"}' '{"sub":"ana","tenant_id":"wayne"}' "$SECRET")"
status_is 401 "a kid naming a tenant the catalog doesn't have"

# --- the legacy secret and an unknown kid, as with static keys
req GET /tenant "" -H "Authorization: Bearer $(sign_header '{"alg":"HS256","typ":"JWT"}' '{"sub":"ana","tenant_id":"acme"}' "$SECRET")"
status_is 200 "a token without kid verifies with the legacy secret"
req GET /tenant "" -H "Authorization: Bearer $(sign_header '{"alg":"HS256","typ":"JWT","kid":"0123456789abcdef"}' '{"sub":"ana","tenant_id":"acme"}' "$SECRET")"
status_is 401 "an unknown kid"

# --- the rotation: at most ROTATE + PROPAGATION seconds (plus a reload)
# after the first key was born, a new key signs
LIMIT=$((ROTATE + PROPAGATION + 5))
WAITED=0
TOKEN2="$TOKEN1"
KID2="$KID1"
while [ "$KID2" = "$KID1" ] && [ $WAITED -lt $LIMIT ]; do
  sleep 1
  WAITED=$((WAITED + 1))
  TOKEN2="$(login acme ana)"
  KID2="$(kid "$TOKEN2")"
done
tenant_kid acme "$KID2" && ok || fail "the second key's kid (got '$KID2')"
[ "$KID2" != "$KID1" ] && ok || fail "a new key signs within $LIMIT s (still '$KID1')"
req GET /tenant "" -H "Authorization: Bearer $TOKEN2"
status_is 200 "a token of the new key"
req GET /tenant "" -H "Authorization: Bearer $TOKEN1"
status_is 200 "a token of the previous key still verifies after the rotation"
body_is '{"tenant":"acme","mode":"dedicated"}' "a token of the previous key"
# And one more rotation: the key before still verifies, the chain goes on.
WAITED=0
KID3="$KID2"
while [ "$KID3" = "$KID2" ] && [ $WAITED -lt $LIMIT ]; do
  sleep 1
  WAITED=$((WAITED + 1))
  TOKEN3="$(login acme ana)"
  KID3="$(kid "$TOKEN3")"
done
[ "$KID3" != "$KID2" ] && [ "$KID3" != "$KID1" ] && ok || fail "a third key (got '$KID3')"
req GET /tenant "" -H "Authorization: Bearer $TOKEN1"
status_is 200 "the first key's token, two rotations later"
req GET /tenant "" -H "Authorization: Bearer $TOKEN2"
status_is 200 "the second key's token, one rotation later"

# --- a second instance on the same store
if [ -n "$PORT2" ]; then
  # same_key [OLD]: both sign with one key (other than OLD), within a
  # rotation, a reload and a propagation (the second may have loaded the keys
  # before the last rotation; a rotation happens on a request, not by time).
  same_key() {
    WAITED=0
    KID_A="$(kid "$(login acme ana)")"
    KID_B="$(kid "$(on2 login acme ana)")"
    while { [ "$KID_A" != "$KID_B" ] || [ "$KID_A" = "${1:-}" ]; } && [ $WAITED -lt $LIMIT ]; do
      sleep 1
      WAITED=$((WAITED + 1))
      KID_A="$(kid "$(login acme ana)")"
      KID_B="$(kid "$(on2 login acme ana)")"
    done
  }
  same_key
  [ "$KID_A" = "$KID_B" ] && ok || fail "both instances sign with one key (first '$KID_A', second '$KID_B')"
  TOKEN_B="$(on2 login globex bia)"
  req GET /tenant "" -H "Authorization: Bearer $TOKEN_B"
  status_is 200 "the first instance verifies the second's token"
  body_is '{"tenant":"globex","mode":"dedicated"}' "the second instance's token"
  on2 req GET /tenant "" -H "Authorization: Bearer $TOKEN1"
  status_is 200 "the second instance verifies the first's oldest token"
  on2 req GET /tenant "" -H "Authorization: Bearer $TOKEN3"
  status_is 200 "the second instance verifies the first's newest token"
  # Both keep rotating on one store, each asking for every generation: one
  # key per generation, whoever stores it. Requests on both for a while, then
  # they agree on a newer key.
  BEFORE="$KID_A"
  END=$((ROTATE + PROPAGATION + 2))
  WAITED=0
  while [ $WAITED -lt $END ]; do
    login acme ana >/dev/null
    on2 login acme ana >/dev/null
    sleep 1
    WAITED=$((WAITED + 1))
  done
  same_key "$BEFORE"
  [ "$KID_A" = "$KID_B" ] && ok || fail "after racing, one key again (first '$KID_A', second '$KID_B')"
  [ "$KID_A" != "$BEFORE" ] && ok || fail "they kept rotating (still '$BEFORE')"
fi

rm -rf "$T"
echo "$CHECKS checks, $FAILS failed"
[ "$FAILS" -eq 0 ]
